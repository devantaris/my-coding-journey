#days of week
num=int(input("Enter the number between 1 to 7: "))
if(num==1):
    print("monday")
elif(num==2):
    print("tuesday")
elif(num==3):
    print("wednessday")
elif(num==4):
    print("thursday")
elif(num==5):
    print("friday")
elif(num==6):
    print("saturday")
elif(num==7):
    print("sunday")
else:
    print("enter a valid number")